function merge(file, farm) {
  const p = path.join(__dirname, "..", "messages", file);
  const data = JSON.parse(fs.readFileSync(p, "utf8"));
  data.farm = farm;
  if (data.nav) data.nav.myFarm = file.startsWith("hy")
    ? "Իմ ֆերմա"
    : file.startsWith("ru")
      ? "Моя ферма"
      : "My farm";
  if (data.megaMenu) {
    data.megaMenu.categories = data.megaMenu.categories || {};
    data.megaMenu.categories.farmOs = {
      label: file.startsWith("hy") ? "Ֆերմայի OS" : file.startsWith("ru") ? "Farm OS" : "Farm OS",
      desc: file.startsWith("hy")
        ? "Եղանակ, ծախսեր, պահեստ, գյուղ"
        : file.startsWith("ru")
          ? "Погода, затраты, склад, село"
          : "Weather, costs, storage, village",
    };
    data.megaMenu.groups = data.megaMenu.groups || {};
    data.megaMenu.groups.farmOps = file.startsWith("hy")
      ? "Գործիքներ"
      : file.startsWith("ru")
        ? "Инструменты"
        : "Tools";
    data.megaMenu.groups.farmVillage = file.startsWith("hy")
      ? "Գյուղ"
      : file.startsWith("ru")
        ? "Село"
        : "Village";
    data.megaMenu.subs = data.megaMenu.subs || {};
    Object.assign(data.megaMenu.subs, {
      farmHub: file.startsWith("hy") ? "Իմ ֆերմա" : file.startsWith("ru") ? "Моя ферма" : "My farm",
      farmRisks: farm.tools.risks.title,
      farmDiary: farm.tools.diary.title,
      farmCosts: farm.tools.costs.title,
      farmSpaces: farm.tools.spaces.title,
      farmReturns: farm.tools.returns.title,
      farmScore: farm.tools.score.title,
      farmRadar: farm.tools.radar.title,
      farmTogether: farm.tools.together.title,
    });
  }
  fs.writeFileSync(p, JSON.stringify(data, null, 2) + "\n");
  console.log("merged", file);
}

